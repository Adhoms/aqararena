// Builds the AqarArena logo mark: Egypt drawn in dots, from the real border used by the site's map.
// Dots grow near the Nile and the coasts (where the projects are) and shrink in the desert; Cairo is solid.
//
//   node scripts/build-logo-mark.mjs
//
// Writes src/components/logo-mark-data.ts (header/footer mark) and src/app/icon.svg (browser tab icon,
// coarser and with larger dots so it stays readable at 16px). Re-run only if the design changes.
import fs from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");
const t = fs.readFileSync(path.join(root, "src/components/egypt-map-data.ts"), "utf8");
const E = JSON.parse(t.slice(t.indexOf("{"), t.lastIndexOf("}") + 1));

function polys(d) {
  const out = [];
  let cur = null;
  for (const m of d.matchAll(/([ML])\s*([-\d.]+)[ ,]([-\d.]+)/g)) {
    if (m[1] === "M") out.push((cur = [[+m[2], +m[3]]]));
    else cur.push([+m[2], +m[3]]);
  }
  return out;
}
function inside([x, y], poly) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}
function segDist([px, py], [ax, ay], [bx, by]) {
  const dx = bx - ax, dy = by - ay;
  const k = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy || 1)));
  return Math.hypot(px - (ax + k * dx), py - (ay + k * dy));
}
const lineDist = (p, pts) => pts.slice(1).reduce((m, b, i) => Math.min(m, segDist(p, pts[i], b)), Infinity);

const border = polys(E.border);
const nile = [...polys(E.nile), ...polys(E.rosetta), ...polys(E.damietta)];
const cairo = E.cities.find((c) => c.id === "cairo").xy;

// Fit the drawing into a 40×40 box.
const [[bx0, by0], [bx1, by1]] = E.bbox;
const S = 31 / Math.max(bx1 - bx0, by1 - by0);
const ox = 20 - ((bx0 + bx1) / 2) * S, oy = 20.5 - ((by0 + by1) / 2) * S;
const toMap = ([x, y]) => [(x - ox) / S, (y - oy) / S];

/** Dots [cx, cy, r, opacity] on a grid of `step` units; `scale` enlarges the dots. */
function dots(step, scale, cairoRadius) {
  const out = [];
  for (let y = 4; y <= 36; y += step) {
    for (let x = 4; x <= 36; x += step) {
      const m = toMap([x, y]);
      if (!border.some((poly) => inside(m, poly))) continue;
      const near = Math.hypot(m[0] - cairo[0], m[1] - cairo[1]) < cairoRadius;
      const d = Math.min(...nile.map((l) => lineDist(m, l)), lineDist(m, border[0]) * 1.6);
      const k = Math.max(0, 1 - d / 170);
      const r = near ? 1.25 : 0.35 + k * 0.75;
      const o = near ? 1 : 0.35 + k * 0.5;
      out.push([+x.toFixed(2), +y.toFixed(2), +(r * scale).toFixed(2), +o.toFixed(2)]);
    }
  }
  return out;
}

const mark = dots(2.2, 1, 45);
fs.writeFileSync(
  path.join(root, "src/components/logo-mark-data.ts"),
  "// Generated by scripts/build-logo-mark.cjs: Egypt in dots, [cx, cy, r, opacity] in a 40×40 box.\n" +
    `export const LOGO_DOTS: [number, number, number, number][] = ${JSON.stringify(mark)};\n`,
);

const tab = dots(3.6, 1.55, 70);
const circles = tab.map(([x, y, r, o]) => `<circle cx="${x}" cy="${y}" r="${r}"${o < 1 ? ` fill-opacity="${o}"` : ""}/>`).join("");
fs.writeFileSync(
  path.join(root, "src/app/icon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40"><rect width="40" height="40" rx="10" fill="#1d4a42"/><g fill="#e2a84a">${circles}</g></svg>\n`,
);
console.log(`mark: ${mark.length} dots, tab icon: ${tab.length} dots`);
